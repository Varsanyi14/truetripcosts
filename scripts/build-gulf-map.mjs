// Gulf locator map generator (authoring tool, NOT part of the site build).
//
// Produces src/data/maps/gulf.js, the hero map for /compare/gulf. Same output shape
// as the other cluster maps, rendered by src/components/RegionMap.astro.
//
// Source data: Natural Earth Admin 0 countries, via the world-atlas package.
// Natural Earth is public domain, so no attribution is required.
//
// ONE DELIBERATE DIFFERENCE from scripts/build-region-map.mjs: this map is built from
// the 50m dataset, not 110m. The Gulf is a small window and 110m drops Bahrain from the
// geometry entirely (it is too small to survive that generalisation) while reducing Qatar
// and Kuwait to blobs. 50m keeps all six as real shapes. The finer coastline is confined
// to this one map, which is the honest trade for a zoomed-in region.
//
// To run (dev deps only, they are not site dependencies):
//   npm i -D world-atlas topojson-client d3-geo
//   node scripts/build-gulf-map.mjs
import { readFileSync, writeFileSync } from "fs";
import * as topojson from "topojson-client";
import { geoMercator, geoPath, geoBounds } from "d3-geo";

const topo = JSON.parse(readFileSync("node_modules/world-atlas/countries-50m.json", "utf8"));
const fc = topojson.feature(topo, topo.objects.countries);

const HIGHLIGHT = {
  "United Arab Emirates": "AE", Oman: "OM", Qatar: "QA",
  "Saudi Arabia": "SA", Bahrain: "BH", Kuwait: "KW"
};

// Backdrop = countries whose bounding box intersects the Arabian peninsula window,
// giving soft geographic context (Iran, Iraq, Yemen, the Red Sea side) around the six.
const BBOX = { lonMin: 32, lonMax: 64, latMin: 11, latMax: 34 };
function intersects(f) {
  const [[x0, y0], [x1, y1]] = geoBounds(f);
  return !(x1 < BBOX.lonMin || x0 > BBOX.lonMax || y1 < BBOX.latMin || y0 > BBOX.latMax);
}

const highlightFeatures = fc.features.filter(f => HIGHLIGHT[f.properties.name]);
const backdropFeatures = fc.features.filter(f => !HIGHLIGHT[f.properties.name] && intersects(f));

const W = 1000, H = 1000, PAD = 60;
// Fit the projection to the six highlighted countries so they frame the map;
// neighbours render in the same projection as backdrop.
const proj = geoMercator();
proj.fitExtent([[PAD, PAD], [W - PAD, H - PAD]], { type: "FeatureCollection", features: highlightFeatures });
const path = geoPath(proj);

function roundD(d) {
  return d ? d.replace(/-?\d+\.?\d*/g, n => {
    const v = Math.round(parseFloat(n) * 10) / 10;
    return (Number.isFinite(v) ? v : 0).toString();
  }) : "";
}

const backdrop = backdropFeatures.map(f => roundD(path(f))).filter(Boolean);
const highlight = highlightFeatures
  .map(f => {
    const c = path.centroid(f);
    return {
      iso: HIGHLIGHT[f.properties.name],
      name: f.properties.name,
      d: roundD(path(f)),
      cx: Math.round(c[0] * 10) / 10,
      cy: Math.round(c[1] * 10) / 10
    };
  })
  .sort((a, b) => a.cx - b.cx); // west to east

// viewBox is framed on the SIX, then opened up by a margin so neighbours bleed in as
// context and clip at the edge (the svg sets overflow:hidden). Framing on everything
// drawn would not work here: the backdrop runs from Egypt to Pakistan and would shrink
// the Gulf to a speck.
let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
for (const f of highlightFeatures) {
  const b = path.bounds(f);
  if (!Number.isFinite(b[0][0])) continue;
  x0 = Math.min(x0, b[0][0]); y0 = Math.min(y0, b[0][1]);
  x1 = Math.max(x1, b[1][0]); y1 = Math.max(y1, b[1][1]);
}
const r1 = n => Math.round(n * 10) / 10;
const MARGIN = 0.06; // share of the larger dimension added on every side
const m = Math.max(x1 - x0, y1 - y0) * MARGIN;
x0 -= m; y0 -= m; x1 += m; y1 += m;
const vbW = r1(x1 - x0), vbH = r1(y1 - y0);
const viewBox = `${r1(x0)} ${r1(y0)} ${vbW} ${vbH}`;

// Emphasis ring on Bahrain only. The other five read on their own at this framing,
// but Bahrain is a speck beside Saudi Arabia and would otherwise be missed. This is
// the same use the Singapore ring gets on the Southeast Asia map and the Hong Kong
// ring on East Asia: mark the one that is too small to see, not every member.
// Ringing Qatar too was tried and dropped, its ring collides with Bahrain's.
const MARK = ["BH"];
const r = r1(vbW * 0.025);
const markers = highlight.filter(h => MARK.includes(h.iso)).map(h => ({ cx: h.cx, cy: h.cy, r }));

const data = { viewBox, backdrop, highlight, markers };

const js = `// AUTO-GENERATED by scripts/build-gulf-map (Natural Earth 50m, public domain).
// Do not hand-edit. Regenerate to change the framing or the highlighted set.
// The Gulf: Kuwait, Bahrain, Qatar, Saudi Arabia, the United Arab Emirates and Oman
// highlighted. Built from 50m rather than 110m because 110m drops Bahrain entirely.
export default ${JSON.stringify(data, null, 1)};
`;
writeFileSync("src/data/maps/gulf.js", js);

const bytes = Buffer.byteLength(js, "utf8");
console.log("countries: highlight =", highlight.length, "| backdrop =", backdrop.length);
console.log("highlight order (W->E):", highlight.map(h => h.iso).join(", "));
console.log("viewBox:", viewBox, "| marker r:", r);
console.log("module size:", (bytes / 1024).toFixed(1), "KB");
console.log("centroids:", highlight.map(h => `${h.iso}(${h.cx},${h.cy})`).join(" "));
