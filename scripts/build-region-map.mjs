// Region locator map generator (authoring tool, NOT part of the site build).
//
// Produces the projected SVG path data for a comparison cluster's hero map, e.g.
// src/data/maps/southern-europe.js. The site itself has no map dependencies; the
// paths are pre-baked into a static module and rendered by src/components/RegionMap.astro.
//
// Source data: Natural Earth 1:110m Admin 0 countries, via the world-atlas package.
// Natural Earth is public domain, so no attribution is required.
//
// To run (install the three dev deps first, they are not site dependencies):
//   npm i -D world-atlas topojson-client d3-geo
//   node scripts/build-region-map.mjs
//
// To make a new cluster (e.g. Southeast Asia), copy this file, change HIGHLIGHT,
// the BBOX window, and the output path, then run it and drop the module in src/data/maps/.
import * as topojson from "topojson-client";
import { geoMercator, geoPath, geoBounds } from "d3-geo";

const topo = JSON.parse(readFileSync("node_modules/world-atlas/countries-110m.json", "utf8"));
const fc = topojson.feature(topo, topo.objects.countries);

const HIGHLIGHT = {
  Portugal: "PT", Spain: "ES", Italy: "IT", Greece: "GR", Croatia: "HR"
};

// Backdrop = countries whose bounding box intersects the Mediterranean/Southern
// Europe window. Gives a soft geographic context around the five.
const BBOX = { lonMin: -12, lonMax: 30, latMin: 30, latMax: 52 };
function intersects(f) {
  const [[x0, y0], [x1, y1]] = geoBounds(f);
  return !(x1 < BBOX.lonMin || x0 > BBOX.lonMax || y1 < BBOX.latMin || y0 > BBOX.latMax);
}

const highlightFeatures = fc.features.filter(f => HIGHLIGHT[f.properties.name]);
const backdropFeatures = fc.features.filter(f => !HIGHLIGHT[f.properties.name] && intersects(f));

const W = 800, H = 360, PAD = 34;
// Fit the projection to the five highlighted countries (with padding) so they
// frame the band; neighbors render in the same projection and clip to the box.
const proj = geoMercator();
proj.fitExtent([[PAD, PAD], [W - PAD, H - PAD]], { type: "FeatureCollection", features: highlightFeatures });
const path = geoPath(proj);

// Round the numbers in a path's d string to 1 decimal to keep the module small.
function roundD(d) {
  return d ? d.replace(/-?\d+\.?\d*/g, n => {
    const v = Math.round(parseFloat(n) * 10) / 10;
    return (Number.isFinite(v) ? v : 0).toString();
  }) : "";
}

const backdrop = backdropFeatures.map(f => roundD(path(f))).filter(Boolean);
const highlight = highlightFeatures
  .map(f => {
    const c = path.centroid(f);
    return {
      iso: HIGHLIGHT[f.properties.name],
      name: f.properties.name,
      d: roundD(path(f)),
      cx: Math.round(c[0] * 10) / 10,
      cy: Math.round(c[1] * 10) / 10
    };
  })
  .sort((a, b) => a.cx - b.cx); // west to east

const data = { viewBox: `0 0 ${W} ${H}`, backdrop, highlight };

const js = `// AUTO-GENERATED by scripts/build-region-map (Natural Earth 110m, public domain).
// Do not hand-edit. Regenerate to change the framing or the highlighted set.
// Southern Europe: Portugal, Spain, Italy, Greece, Croatia highlighted.
export default ${JSON.stringify(data, null, 1)};
`;
writeFileSync("out/southern-europe.js", js);

const bytes = Buffer.byteLength(js, "utf8");
console.log("countries: highlight =", highlight.length, "| backdrop =", backdrop.length);
console.log("highlight order (W->E):", highlight.map(h => h.iso).join(", "));
console.log("module size:", (bytes / 1024).toFixed(1), "KB");
console.log("centroids:", highlight.map(h => `${h.iso}(${h.cx},${h.cy})`).join(" "));
